"""Profile validation and AHK v2 script generation."""
import json
import pathlib

from . import keys

from .paths import DATA_FILE as DATA

DEFAULT_SETTINGS = {
    "menuKey": "LCtrl",
    "menuMode": "hold",
    "keyDelayMs": 30,
    "chainTimeoutMs": 1000,
    "passThrough": True,
    "gameExe": "helldivers2.exe",
    "arrowKeys": {"U": "Up", "D": "Down", "L": "Left", "R": "Right"},
}


class ProfileError(ValueError):
    pass


def load_catalog(path=DATA):
    """Return {name: code}. Duplicate names must agree on the code."""
    cat = {}
    with open(path, encoding="utf-8") as fh:
        rows = json.load(fh)
    for row in rows:
        if cat.setdefault(row["name"], row["code"]) != row["code"]:
            raise ProfileError(f"catalog has conflicting codes for {row['name']}")
    return cat


def _int(settings, name, lo, hi):
    v = settings[name]
    if isinstance(v, bool) or not isinstance(v, int) or not lo <= v <= hi:
        raise ProfileError(f"settings.{name} must be an integer {lo}..{hi}")
    return v


def validate(profile, catalog):
    """Return (settings, bindings) with canonical key names, or raise ProfileError."""
    if not isinstance(profile, dict) or profile.get("version") != 1:
        raise ProfileError("profile.version must be 1")
    settings = {**DEFAULT_SETTINGS, **profile.get("settings", {})}
    settings["arrowKeys"] = {**DEFAULT_SETTINGS["arrowKeys"],
                             **profile.get("settings", {}).get("arrowKeys", {})}

    menu = keys.canon(settings["menuKey"])
    if menu not in keys.MENU_KEYS:
        raise ProfileError(f"settings.menuKey must be one of {sorted(keys.MENU_KEYS)}")
    settings["menuKey"] = menu
    if settings["menuMode"] != "hold":
        raise ProfileError('settings.menuMode: only "hold" is supported')
    _int(settings, "keyDelayMs", 1, 500)
    _int(settings, "chainTimeoutMs", 100, 5000)
    if not isinstance(settings["passThrough"], bool):
        raise ProfileError("settings.passThrough must be true or false")
    if not isinstance(settings["gameExe"], str) or not keys.GAME_EXE_RE.match(settings["gameExe"]):
        raise ProfileError("settings.gameExe must look like name.exe")
    arrows = {}
    for d in "UDLR":
        k = keys.canon(settings["arrowKeys"].get(d))
        if k is None:
            raise ProfileError(f"settings.arrowKeys.{d} is not an allowed key")
        arrows[d] = k
    settings["arrowKeys"] = arrows
    reserved = {menu, *arrows.values()}

    bindings, seen = [], set()
    for i, b in enumerate(profile.get("bindings", [])):
        where = f"bindings[{i}]"
        name = b.get("stratagem") if isinstance(b, dict) else None
        if name not in catalog:
            raise ProfileError(f"{where}: unknown stratagem {name!r}")
        trig = b.get("trigger")
        if not isinstance(trig, list) or not trig:
            raise ProfileError(f"{where}: trigger must be a non-empty list")
        canon = []
        for k in trig:
            c = keys.canon(k)
            if c is None:
                raise ProfileError(f"{where}: key {k!r} is not allowed")
            if c in reserved:
                raise ProfileError(f"{where}: {c} is the menu or direction key and cannot be a trigger")
            canon.append(c)
        tid = tuple(x.lower() for x in canon)
        if tid in seen:
            raise ProfileError(f"{where}: trigger {'+'.join(canon)} is already bound")
        seen.add(tid)
        bindings.append({"trigger": canon, "stratagem": name, "code": catalog[name]})

    singles = {b["trigger"][0] for b in bindings if len(b["trigger"]) == 1}
    chains = [b for b in bindings if len(b["trigger"]) > 1]
    chain_keys = {k for b in chains for k in b["trigger"]}
    for k in sorted(singles & chain_keys):
        raise ProfileError(f"{k} is used both as a single trigger and inside a chain")
    ids = [tuple(x.lower() for x in b["trigger"]) for b in chains]
    for a in ids:
        for c in ids:
            if a != c and c[:len(a)] == a:
                raise ProfileError(f"chain {' > '.join(a)} is a prefix of chain {' > '.join(c)}")
    return settings, bindings


def _q(s):
    """AHK v2 double-quoted string literal. Inputs are already allowlisted."""
    return '"' + s.replace("`", "``").replace('"', '`"') + '"'


def generate(profile, catalog, profile_name="profile"):
    settings, bindings = validate(profile, catalog)
    pre = "~*" if settings["passThrough"] else "*"
    singles = [b for b in bindings if len(b["trigger"]) == 1]
    chains = [b for b in bindings if len(b["trigger"]) > 1]
    L = []
    w = L.append
    w(f"; Generated by Macro Hub from profile: {''.join(c for c in profile_name if c.isprintable() and c not in chr(10)+chr(13))}")
    w("#Requires AutoHotkey v2.0")
    w("#SingleInstance Force")
    w("Persistent  ; keep running even with no hotkeys, so the hub shows it as running")
    w("")
    w(f"MenuKey := {_q(settings['menuKey'])}")
    w(f"KeyDelay := {settings['keyDelayMs']}")
    w(f"ChainTimeoutMs := {settings['chainTimeoutMs']}")
    w("Dirs := Map(" + ", ".join(f'"{d}", {_q(k)}' for d, k in settings["arrowKeys"].items()) + ")")
    w("Busy := false")
    w("ChainProgress := []")
    w("Chains := Map()")
    for b in chains:
        cid = "".join(k.lower() + "|" for k in b["trigger"])
        w(f"Chains[{_q(cid)}] := {_q(b['code'])}  ; {b['stratagem']}")
    w("")
    w("CallStratagem(code) {")
    w("    global Busy")
    w("    if Busy")
    w("        return")
    w("    Busy := true")
    w("    try {")
    w('        Send "{" MenuKey " down}"')
    w("        Sleep KeyDelay * 2")
    w("        for ch in StrSplit(code) {")
    w("            k := Dirs[ch]")
    w('            Send "{" k " down}"')
    w("            Sleep KeyDelay")
    w('            Send "{" k " up}"')
    w("            Sleep KeyDelay")
    w("        }")
    w("    } finally {")
    w('        Send "{" MenuKey " up}"')
    w("        Busy := false")
    w("    }")
    w("}")
    w("")
    w("ChainHasPrefix(prefix) {")
    w("    for id in Chains {")
    w("        if SubStr(id, 1, StrLen(prefix)) = prefix")
    w("            return true")
    w("    }")
    w("    return false")
    w("}")
    w("")
    w("ResetChain() {")
    w("    global ChainProgress")
    w("    ChainProgress := []")
    w("}")
    w("")
    w("ChainKey(key) {")
    w("    global ChainProgress")
    w("    SetTimer ResetChain, 0")
    w("    ChainProgress.Push(key)")
    w("    prefix := ''")
    w("    for k in ChainProgress")
    w("        prefix .= k '|'")
    w("    if !ChainHasPrefix(prefix) {")
    w("        ChainProgress := [key]")
    w("        prefix := key '|'")
    w("        if !ChainHasPrefix(prefix) {")
    w("            ChainProgress := []")
    w("            return")
    w("        }")
    w("    }")
    w("    if Chains.Has(prefix) {")
    w("        code := Chains[prefix]")
    w("        ChainProgress := []")
    w("        CallStratagem(code)")
    w("        return")
    w("    }")
    w("    SetTimer ResetChain, -ChainTimeoutMs")
    w("}")
    w("")
    w(f"#HotIf WinActive({_q('ahk_exe ' + settings['gameExe'])})")
    for b in singles:
        k = b["trigger"][0]
        w(f"{pre}{k}:: CallStratagem({_q(b['code'])})  ; {b['stratagem']}")
    seen = []
    for b in chains:
        for k in b["trigger"]:
            if k not in seen:
                seen.append(k)
    for k in seen:
        w(f"{pre}{k}:: ChainKey({_q(k.lower())})")
    w("#HotIf")
    return "\n".join(L) + "\n"


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="Generate an AHK v2 script from a profile JSON")
    ap.add_argument("profile")
    ap.add_argument("output")
    a = ap.parse_args(argv)
    p = pathlib.Path(a.profile)
    script = generate(json.loads(p.read_text(encoding="utf-8")), load_catalog(), p.stem)
    pathlib.Path(a.output).write_text(script, encoding="utf-8-sig")  # BOM: AHK reads UTF-8 reliably
    print("wrote", a.output)


if __name__ == "__main__":
    main()

